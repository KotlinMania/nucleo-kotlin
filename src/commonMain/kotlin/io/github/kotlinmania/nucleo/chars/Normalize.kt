package io.github.kotlinmania.nucleo.chars

/**
 * Normalize a Unicode character by converting Latin characters which are variants
 * of ASCII characters to their latin equivalent.
 *
 * If a character does not normalize to a single ASCII character, no normalization is performed.
 *
 * This performs normalization within the following Unicode blocks:
 * - Latin-1 Supplement
 * - Latin Extended-A
 * - Latin Extended-B
 * - Latin Extended Additional
 * - Superscripts and Subscripts
 *
 * If the character does not fall in this block, it is not normalized.
 */
public fun normalize(c: Char): Char {
    val code = c.code
    // outside checked blocks
    if (code < 0x00A0 || code >= 0x20A0) {
        return c
    }
    // Latin-1 Supplement, Extended-A, Extended-B
    if (code <= 0x029F) {
        return LATIN_1AB[code - 0x00A0]
    }
    // between blocks
    if (code < 0x1E00) {
        return c
    }
    // Latin Extended Additional
    if (code <= 0x1EFF) {
        return LATIN_EXTENDED_ADDITIONAL[code - 0x1E00]
    }
    // between blocks
    if (code < 0x2070) {
        return c
    }
    // Superscripts and subscripts
    return SUPERSCRIPTS_AND_SUBSCRIPTS[code - 0x2070]
}

public fun normalize(c: Int): Int {
    if (c in 0..0xFFFF) {
        return normalize(c.toChar()).code
    }
    return c
}

